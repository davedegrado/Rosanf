ACCENTS = {  # lettera base, accento grave(\) o acuto(/)
    "À": ("A", "\\"), "È": ("E", "\\"), "É": ("E", "/"),
    "Ì": ("I", "\\"), "Ò": ("O", "\\"), "Ù": ("U", "\\"),
}

CELL_W, CELL_H, BASE = 6, 10, 9


def build(png_path, fnt_path):
    chars = list(GLYPHS.keys()) + list(ACCENTS.keys()) + [" "]
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    sheet_w, sheet_h = 128, 128
    assert rows * CELL_H <= sheet_h
    cv = Canvas(sheet_w, sheet_h)
    entries = []  # (codepoint, x, y, w, advance)
    for i, ch in enumerate(chars):
        x0, y0 = (i % cols) * (CELL_W + 2), (i // cols) * CELL_H
        if ch == " ":
            entries.append((32, x0, y0, 1, 4))
            continue
        if ch in ACCENTS:
            base, acc = ACCENTS[ch]
            rows_ = GLYPHS[base]
            if acc == "\\":
                cv.set(x0 + 1, y0 + 0, "w")
                cv.set(x0 + 2, y0 + 1, "w")
            else:
                cv.set(x0 + 3, y0 + 0, "w")
                cv.set(x0 + 2, y0 + 1, "w")
        else:
            rows_ = GLYPHS[ch]
        gw = len(rows_[0])
        for j, row in enumerate(rows_):
            for k, p in enumerate(row):
                if p == "#":
                    cv.set(x0 + k, y0 + 2 + j, "w")
        entries.append((ord(ch), x0, y0, gw, gw + 1))
    cv.save(png_path)

    lines = [
        'info face="Nokia3310" size=10 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
        f"common lineHeight={CELL_H + 1} base={BASE} scaleW={sheet_w} scaleH={sheet_h} pages=1 packed=0",
        'page id=0 file="nokia.png"',
    ]
    out = []
    for cp, x, y, w, adv in entries:
        out.append((cp, x, y, w, adv))
        ch = chr(cp)
        # minuscole -> stesso glifo delle maiuscole (stile display Nokia)
        if ch.isalpha() and ch.upper() == ch and ch.lower() != ch:
            out.append((ord(ch.lower()), x, y, w, adv))
    lines.append(f"chars count={len(out)}")
    for cp, x, y, w, adv in out:
        lines.append(
            f"char id={cp} x={x} y={y} width={w} height={CELL_H} xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15"
        )
    with open(fnt_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def text_canvas(text, color="w", scale=1):
    """Rende del testo col font Nokia su un Canvas (per logo e immagini)."""
    width = 0
    for ch in text:
        if ch == " ":
            width += 4
        else:
            g = GLYPHS.get(ch.upper(), GLYPHS["?"])
            width += len(g[0]) + 1
    cv = Canvas(max(1, width), CELL_H)
    x = 0
    for ch in text:
        if ch == " ":
            x += 4
            continue
        g = GLYPHS.get(ch.upper(), GLYPHS["?"])
        for j, row in enumerate(g):
            for k, p in enumerate(row):
                if p == "#":
                    cv.set(x + k, 2 + j, color)
        x += len(g[0]) + 1
    return cv.scaled(scale) if scale > 1 else cv
